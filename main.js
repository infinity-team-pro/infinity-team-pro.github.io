function drawStars(canvas) {
  const hero = canvas.parentElement;
  const w = hero.clientWidth, h = hero.clientHeight;
  const dpr = Math.min(window.devicePixelRatio || 1, 2);
  canvas.width = Math.round(w * dpr);
  canvas.height = Math.round(h * dpr);
  const ctx = canvas.getContext("2d");
  ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
  let seed = 11;                                   // одинаковое небо при каждой загрузке
  const rnd = () => (seed = (seed * 16807) % 2147483647) / 2147483647;
  const count = Math.round((w * h) / 7000);
  for (let i = 0; i < count; i++) {
    const big = rnd() < 0.1;
    ctx.globalAlpha = 0.3 + rnd() * 0.6;
    ctx.fillStyle = rnd() < 0.15 ? "#FFE9A8" : "#FFFFFF";
    ctx.beginPath();
    ctx.arc(rnd() * w, rnd() * h, big ? 1.4 + rnd() : 0.5 + rnd() * 0.8, 0, Math.PI * 2);
    ctx.fill();
  }
}

const starCanvas = document.querySelector(".stars");
if (starCanvas) {
  drawStars(starCanvas);
  let t;
  window.addEventListener("resize", () => { clearTimeout(t); t = setTimeout(() => drawStars(starCanvas), 150); });
}

/* ---------- сцена: строители строят компании — они приносят деньги клиенту ---------- */

const C = {
  grass: "#4B974B", dirt: "#7C5C46", darkDirt: "#5E4535", stone: "#A3A2A5", trunk: "#694028",
  leaf: "#287F47", yellow: "#F5CD30", blue: "#0D69AC", lime: "#A4BD47", red: "#C4281C",
  orange: "#DA8541", wall: "#EEF1F8", glass: "#7E9BDA", door: "#5E4535", suit: "#24365F",
  hat: "#1B2A35", brief: "#7C5C46", flower: "#F5CD30"
};
const TW = 44, TH = 22, CH = 25;              // ромб клетки и высота кубика
const iso = (x, y, h) => ({ x: (x - y) * TW / 2, y: (x + y) * TH / 2 - h * CH });

function shade(hex, k) {
  const n = parseInt(hex.slice(1), 16);
  const ch = (v) => Math.max(0, Math.min(255, Math.round(v * k)));
  return `rgb(${ch(n >> 16)}, ${ch((n >> 8) & 255)}, ${ch(n & 255)})`;
}

function buildScene(svg) {
  const reduce = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  const cubes = [];
  // role: island — появляется сразу; build — строится; actor — человечки
  const add = (x, y, z, top, side = top, o = {}) => {
    const c = { x, y, z, top, side, role: "island", ...o };
    cubes.push(c);
    return c;
  };

  // остров 8×8: сзади слева студия, сзади справа магазин, спереди по центру клиент
  const shape = ["..####..", ".######.", "########", "########", "########", "########", ".######.", "..####.."];
  shape.forEach((row, y) => [...row].forEach((c, x) => {
    if (c !== "#") return;
    add(x, y, 0, C.grass, C.dirt);
    if (x >= 1 && x <= 6 && y >= 1 && y <= 6) add(x, y, -1, C.darkDirt);
    if (x >= 2 && x <= 5 && y >= 2 && y <= 5) add(x, y, -2, C.stone);
  }));
  add(3, 3, -3, C.stone); add(4, 4, -3, C.stone); add(3, 4, -3, C.stone); add(4, 3, -3, C.stone);

  // кусты и цветы — низкие, ничего не закрывают
  [[2.2, 6.7], [6.7, 2.2], [2.4, 1.6]].forEach(([x, y]) => add(x, y, 1, C.leaf, C.leaf, { s: 0.6 }));
  [[3.6, 3.3, C.flower], [5.4, 6.6, C.red], [6.6, 5.4, C.flower], [2.7, 4.5, C.red], [4.5, 2.6, C.flower]]
    .forEach(([x, y, col]) => add(x, y, 1, col, col, { s: 0.3 }));

  // две компании 2×2×3: этаж 1 — стены и дверь, этаж 2 — окна, этаж 3 — крыша
  const company = (id, cells, roof, door, windows) => {
    const corner = cells.reduce((a, c) => (c[0] + c[1] > a[0] + a[1] ? c : a));   // ближний угол
    const blocks = [];
    for (let z = 1; z <= 3; z++) cells.forEach(([x, y]) => {
      const k = `${x},${y}`;
      const isDoor = z === 1 && k === door, isWin = z === 2 && windows.includes(k);
      const side = z === 3 ? roof : isDoor ? C.door : isWin ? C.glass : C.wall;
      blocks.push(add(x, y, z, z === 3 ? roof : C.wall, side,
        { role: "build", company: id, win: isWin, corner: x === corner[0] && y === corner[1] }));
    });
    return { id, cells, corner, blocks, roofCenter: iso(cells[0][0] + 0.5, cells[0][1] + 0.5, 3.2) };
  };
  const A = company("A", [[0, 4], [1, 4], [0, 5], [1, 5]], C.red, "0,5", ["0,5", "1,5", "1,4"]);
  const B = company("B", [[4, 0], [5, 0], [4, 1], [5, 1]], C.blue, "5,0", ["4,1", "5,1", "5,0"]);

  // человечек из трёх кубиков поменьше блока (ноги, тело, голова) + головной убор; base — высота, на которой стоит
  const PS = 0.72;
  const person = (who, x, y, base, legs, body, hatColor, hatSize) => {
    const z0 = base + 1;
    add(x, y, z0, legs, legs, { role: "actor", who, s: PS, hs: PS });
    add(x, y, z0 + PS, body, body, { role: "actor", who, s: PS, hs: PS });
    add(x, y, z0 + 2 * PS, C.yellow, C.yellow, { role: "actor", who, s: PS, hs: PS });
    add(x, y, z0 + 3 * PS, hatColor, hatColor, { role: "actor", who, s: hatSize, hs: 0.24 });
  };
  // строители стоят на ближнем углу своей компании (в итоге — на крыше), в оранжевых касках
  person("builderA", ...A.corner, 3, C.lime, C.blue, C.orange, 0.84);
  person("builderB", ...B.corner, 3, C.lime, C.red, C.orange, 0.84);
  // клиент в костюме и шляпе, с портфелем — спереди по центру
  person("client", 6, 6, 0, C.suit, C.suit, C.hat, 0.8);
  add(6.02, 6.5, 1, C.brief, C.brief, { role: "actor", who: "client", s: 0.32 });

  // рисуем от дальних к ближним
  cubes.sort((a, b) => (a.x + a.y) - (b.x + b.y) || a.z - b.z);

  const P = (x, y) => `${x.toFixed(1)},${y.toFixed(1)}`;
  let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
  const markup = cubes.map((b, i) => {
    const s = b.s || 1, hs = b.hs || s;
    const c = iso(b.x, b.y, b.z - 1 + hs);
    const hw = TW * s / 2, hh = TH * s / 2, ch = CH * hs;
    minX = Math.min(minX, c.x - hw); maxX = Math.max(maxX, c.x + hw);
    minY = Math.min(minY, c.y - hh); maxY = Math.max(maxY, c.y + hh + ch);
    const top = [P(c.x, c.y - hh), P(c.x + hw, c.y), P(c.x, c.y + hh), P(c.x - hw, c.y)].join(" ");
    const left = [P(c.x - hw, c.y), P(c.x, c.y + hh), P(c.x, c.y + hh + ch), P(c.x - hw, c.y + ch)].join(" ");
    const right = [P(c.x + hw, c.y), P(c.x, c.y + hh), P(c.x, c.y + hh + ch), P(c.x + hw, c.y + ch)].join(" ");
    b.idx = i;
    return `<g class="b${b.win ? " win" : ""}" data-i="${i}">` +
      `<polygon class="l" points="${left}" fill="${shade(b.side, 0.86)}"/>` +
      `<polygon class="r" points="${right}" fill="${shade(b.side, 0.68)}"/>` +
      `<polygon class="t" points="${top}" fill="${shade(b.top, 1.1)}"/>` +
      `</g>`;
  });

  // луна и звезда, как на картине с бесконечностью
  const moon = { x: minX + 6, y: minY - 30 };
  const star = { x: maxX - 4, y: minY - 16 };
  const padTop = 60, pad = 14, glowY = maxY + 30;
  svg.setAttribute("viewBox", `${minX - pad} ${minY - padTop} ${maxX - minX + pad * 2} ${glowY + 18 - (minY - padTop)}`);

  const badgePos = iso(6, 6, 4.6);
  const badgeY = badgePos.y - 30;
  svg.innerHTML =
    `<path d="M${moon.x + 5},${moon.y - 16} A17,17 0 1,0 ${moon.x + 5},${moon.y + 16} A20,20 0 0,1 ${moon.x + 5},${moon.y - 16}Z" fill="#F5CD30"/>` +
    `<path d="M${star.x},${star.y - 9} l2.6,6.4 6.4,2.6 -6.4,2.6 -2.6,6.4 -2.6,-6.4 -6.4,-2.6 6.4,-2.6z" fill="#F5CD30"/>` +
    `<ellipse cx="${(minX + maxX) / 2}" cy="${glowY}" rx="${(maxX - minX) * 0.3}" ry="11" fill="rgba(150,190,255,0.16)"/>` +
    `<g class="cubes" stroke="rgba(10,23,69,0.22)" stroke-width="0.7" stroke-linejoin="round">${markup.join("")}</g>` +
    `<g class="coins"></g>` +
    `<g class="badge" transform="translate(${badgePos.x},${badgeY})" opacity="0">` +
    `<rect x="-52" y="-17" width="104" height="34" rx="10" fill="#fff"/>` +
    `<path d="M-7 17 L0 25 L7 17z" fill="#fff"/>` +
    `<text text-anchor="middle" y="7" font-family="Onest, system-ui, sans-serif" font-weight="700" font-size="18" fill="#0E1B45">$ 0</text>` +
    `</g>`;

  const el = (b) => svg.querySelector(`.cubes [data-i="${b.idx}"]`);
  const group = (who) => cubes.filter((b) => b.who === who).map(el);
  const badge = svg.querySelector(".badge");
  const badgeText = badge.querySelector("text");

  if (reduce) {                         // без анимации — сразу готовая картинка
    svg.classList.add("lit");
    badge.setAttribute("opacity", "1");
    badgeText.textContent = "$ ∞";
    return;
  }

  const show = (node, delay, from, to = "translateY(0)", duration = 480, easing = "cubic-bezier(.2,.9,.3,1.25)") =>
    node.animate([{ opacity: 0, transform: from }, { opacity: 1, transform: to }], { duration, delay, easing, fill: "both" });

  // 1) остров и люди появляются по слоям (строители — пока на земле: на 3 этажа ниже крыши)
  const LIFT = 3 * CH;
  cubes.filter((b) => b.role !== "build").forEach((b) => {
    const isBuilder = b.who === "builderA" || b.who === "builderB";
    const layer = isBuilder ? b.z - 3 : b.z;
    const end = isBuilder ? `translateY(${LIFT}px)` : "translateY(0)";
    const start = isBuilder ? `translateY(${LIFT - 60}px)` : "translateY(-60px)";
    show(el(b), (layer + 3) * 150 + (b.x + b.y) * 15, start, end);
  });

  // 2) стройка: по этажу за раз. Три блока ставятся, потом строитель прыгает — под ним появляется угловой блок
  let t = 1700;
  for (let z = 1; z <= 3; z++) {
    const restA = A.blocks.filter((b) => b.z === z && !b.corner), restB = B.blocks.filter((b) => b.z === z && !b.corner);
    for (let i = 0; i < 3; i++) {
      show(el(restA[i]), t, "translateY(-34px)", "translateY(0)", 300, "cubic-bezier(.3,1.4,.5,1)");
      show(el(restB[i]), t + 55, "translateY(-34px)", "translateY(0)", 300, "cubic-bezier(.3,1.4,.5,1)");
      t += 115;
    }
    t += 80;
    const from = LIFT - (z - 1) * CH, to = LIFT - z * CH;
    ["builderA", "builderB"].forEach((who) => group(who).forEach((node) => node.animate(
      [{ transform: `translateY(${from}px)` }, { transform: `translateY(${to - 22}px)`, offset: 0.45 }, { transform: `translateY(${to}px)` }],
      { duration: 380, delay: t, easing: "ease-in-out", fill: "forwards" }
    )));
    [A, B].forEach((co) => {
      const cornerBlock = co.blocks.find((b) => b.z === z && b.corner);
      show(el(cornerBlock), t + 150, "scale(0.6)", "scale(1)", 220, "ease-out");
    });
    t += 420;
  }
  const BUILD_END = t;

  // 3) компании открылись — в окнах загорается свет, строители радуются
  const cheer = (who, delay) => group(who).forEach((node) => node.animate(
    [{ transform: "translateY(0)" }, { transform: "translateY(-10px)" }, { transform: "translateY(0)" }],
    { duration: 300, delay, easing: "ease-out", composite: "add" }
  ));
  setTimeout(() => svg.classList.add("lit"), BUILD_END);
  cheer("builderA", BUILD_END + 100); cheer("builderB", BUILD_END + 220);

  // 4) деньги: монеты летят от компаний в счётчик клиента
  const coinsLayer = svg.querySelector(".coins");
  const to = { x: badgePos.x, y: badgeY };
  let total = 0, turn = 0, timer = null;
  const fmt = () => new Intl.NumberFormat(document.documentElement.lang === "en" ? "en-US" : "ru-RU").format(total);

  function flyCoin() {
    const co = turn++ % 2 ? B : A;
    const from = co.roofCenter;
    const mid = { x: (from.x + to.x) / 2, y: Math.min(from.y, to.y) - 60 };
    const g = document.createElementNS("http://www.w3.org/2000/svg", "g");
    g.innerHTML = `<circle r="11" fill="#F5CD30" stroke="#B8921A" stroke-width="2.2"/>` +
      `<text y="5" text-anchor="middle" font-family="Onest, sans-serif" font-weight="700" font-size="14" fill="#8A6500">$</text>`;
    coinsLayer.appendChild(g);
    const frames = [];
    for (let i = 0; i <= 10; i++) {
      const k = i / 10, u = 1 - k;
      const x = u * u * from.x + 2 * u * k * mid.x + k * k * to.x;
      const y = u * u * from.y + 2 * u * k * mid.y + k * k * to.y;
      frames.push({
        transform: `translate(${x}px, ${y}px) scale(${Math.abs(Math.cos(k * Math.PI * 3)) * 0.7 + 0.3}, 1)`,
        opacity: i === 0 ? 0 : i === 10 ? 0.2 : 1
      });
    }
    g.animate(frames, { duration: 900, easing: "ease-in-out" }).onfinish = () => {
      g.remove();
      total += 250;
      badgeText.textContent = `$ ${fmt()}`;
      badge.animate([{ transform: `translate(${badgePos.x}px, ${badgeY}px) scale(1.12)` },
                     { transform: `translate(${badgePos.x}px, ${badgeY}px) scale(1)` }], { duration: 220, easing: "ease-out" });
      cheer("client", 0);
    };
  }

  // монеты летят, только пока сцену видно (бережём батарею)
  let visible = true, started = false;
  const start = () => { if (started && !timer && visible && !document.hidden) { flyCoin(); timer = setInterval(flyCoin, 800); } };
  const stop = () => { clearInterval(timer); timer = null; };
  setTimeout(() => {
    started = true;
    badge.animate([{ opacity: 0 }, { opacity: 1 }], { duration: 400, fill: "forwards" });
    start();
  }, BUILD_END + 600);
  if ("IntersectionObserver" in window) {
    new IntersectionObserver(([e]) => { visible = e.isIntersecting; visible ? start() : stop(); }).observe(svg);
  }
  document.addEventListener("visibilitychange", () => (document.hidden ? stop() : start()));
}

