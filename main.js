/* ---------- остров из кубиков ---------- */

const C = {
  grass: "#4B974B", dirt: "#7C5C46", darkDirt: "#5E4535", stone: "#A3A2A5", trunk: "#694028",
  leaf: "#287F47", yellow: "#F5CD30", blue: "#0D69AC", lime: "#A4BD47", red: "#C4281C"
};

function shade(hex, k) {
  const n = parseInt(hex.slice(1), 16);
  const ch = (v) => Math.max(0, Math.min(255, Math.round(v * k)));
  return `rgb(${ch(n >> 16)}, ${ch((n >> 8) & 255)}, ${ch(n & 255)})`;
}

function buildIsland(svg) {
  const TW = 44, TH = 22, CH = 25;   // ширина и высота ромба, высота кубика
  const blocks = [];
  const add = (x, y, z, top, side = top) => blocks.push({ x, y, z, top, side });

  // форма острова 7×7
  const shape = [
    "..###..",
    ".#####.",
    "#######",
    "#######",
    "#######",
    ".#####.",
    "..###.."
  ];
  shape.forEach((row, y) => [...row].forEach((c, x) => {
    if (c !== "#") return;
    add(x, y, 0, C.grass, C.dirt);                                       // трава
    if (x >= 1 && x <= 5 && y >= 1 && y <= 5) add(x, y, -1, C.darkDirt); // земля
    if (x >= 2 && x <= 4 && y >= 2 && y <= 4) add(x, y, -2, C.stone);    // камень
  }));
  add(3, 3, -3, C.stone);   // остров сужается книзу — парит

  // дерево
  add(4, 1, 1, C.trunk); add(4, 1, 2, C.trunk);
  for (let x = 3; x <= 5; x++) for (let y = 0; y <= 2; y++) {
    if (x === 5 && y === 0) continue;
    add(x, y, 3, C.leaf);
  }
  add(4, 1, 4, C.leaf);

  // классический «нуб»: зелёные ноги, синее тело, жёлтая голова
  add(2, 4, 1, C.lime); add(2, 4, 2, C.blue); add(2, 4, 3, C.yellow);

  // красный блок — как будто его только что поставили
  add(4, 4, 1, C.red);

  // порядок рисования: дальние и нижние — раньше
  blocks.sort((a, b) => (a.x + a.y) - (b.x + b.y) || a.z - b.z);

  const pt = (x, y) => `${x.toFixed(1)},${y.toFixed(1)}`;
  let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
  const parts = blocks.map((b) => {
    const cx = (b.x - b.y) * TW / 2;
    const cy = (b.x + b.y) * TH / 2 - b.z * CH;
    minX = Math.min(minX, cx - TW / 2); maxX = Math.max(maxX, cx + TW / 2);
    minY = Math.min(minY, cy - TH / 2); maxY = Math.max(maxY, cy + TH / 2 + CH);
    const top = [pt(cx, cy - TH / 2), pt(cx + TW / 2, cy), pt(cx, cy + TH / 2), pt(cx - TW / 2, cy)].join(" ");
    const left = [pt(cx - TW / 2, cy), pt(cx, cy + TH / 2), pt(cx, cy + TH / 2 + CH), pt(cx - TW / 2, cy + CH)].join(" ");
    const right = [pt(cx + TW / 2, cy), pt(cx, cy + TH / 2), pt(cx, cy + TH / 2 + CH), pt(cx + TW / 2, cy + CH)].join(" ");
    // строим слоями снизу вверх, внутри слоя — от дальних к ближним
    const delay = (b.z + 3) * 190 + (b.x + b.y) * 22;
    return `<g class="b" style="--d:${delay}ms">` +
      `<polygon points="${left}" fill="${shade(b.side, 0.86)}"/>` +
      `<polygon points="${right}" fill="${shade(b.side, 0.68)}"/>` +
      `<polygon points="${top}" fill="${shade(b.top, 1.1)}"/>` +
      `</g>`;
  });

  const pad = 12;
  const shadowY = maxY + 26;
  const w = maxX - minX + pad * 2;
  const h = shadowY + 14 - minY + pad;
  svg.setAttribute("viewBox", `${minX - pad} ${minY - pad} ${w} ${h}`);
  svg.innerHTML =
    `<ellipse cx="${(minX + maxX) / 2}" cy="${shadowY}" rx="${(maxX - minX) * 0.24}" ry="10" fill="rgba(27,42,53,0.10)"/>` +
    `<g stroke="rgba(27,42,53,0.16)" stroke-width="0.7" stroke-linejoin="round">${parts.join("")}</g>`;

  requestAnimationFrame(() => requestAnimationFrame(() => svg.classList.add("built")));
}

const island = document.getElementById("island");
if (island) buildIsland(island);
