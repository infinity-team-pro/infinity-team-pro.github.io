function drawStars(canvas) {
  const hero = canvas.parentElement;
  const w = hero.clientWidth, h = hero.clientHeight;
  const dpr = Math.min(window.devicePixelRatio || 1, 2);
  canvas.width = Math.round(w * dpr);
  canvas.height = Math.round(h * dpr);
  const ctx = canvas.getContext("2d");
  ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
  let seed = 11;                                   // одинаковое небо при каждой загрузке
  const rnd = () => (seed = (seed * 16807) % 2147483647) / 2147483647;
  const count = Math.round((w * h) / 7000);
  for (let i = 0; i < count; i++) {
    const big = rnd() < 0.1;
    ctx.globalAlpha = 0.3 + rnd() * 0.6;
    ctx.fillStyle = rnd() < 0.15 ? "#FFE9A8" : "#FFFFFF";
    ctx.beginPath();
    ctx.arc(rnd() * w, rnd() * h, big ? 1.4 + rnd() : 0.5 + rnd() * 0.8, 0, Math.PI * 2);
    ctx.fill();
  }
}

const starCanvas = document.querySelector(".stars");
if (starCanvas) {
  drawStars(starCanvas);
  let t;
  window.addEventListener("resize", () => { clearTimeout(t); t = setTimeout(() => drawStars(starCanvas), 150); });
}

