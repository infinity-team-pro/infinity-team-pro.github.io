function storedLang() {
  try { return localStorage.getItem("it-lang"); } catch (e) { return null; }
}

function setLang(lang) {
  const dict = I18N[lang] || I18N.ru;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const text = dict[el.dataset.i18n];
    if (!text) return;
    // data-i18n-html — только для наших же строк с <span class="nw"> (чтобы «Roblox-игры» не разрывались)
    if (el.hasAttribute("data-i18n-html")) el.innerHTML = text;
    else el.textContent = text;
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const text = dict[el.dataset.i18nAria];
    if (text) el.setAttribute("aria-label", text);
  });
  document.title = dict["meta.title"];
  const desc = document.querySelector('meta[name="description"]');
  if (desc) desc.setAttribute("content", dict["meta.desc"]);
  document.querySelectorAll(".lang button").forEach((b) => {
    b.setAttribute("aria-pressed", String(b.dataset.lang === lang));
  });
  try { localStorage.setItem("it-lang", lang); } catch (e) { /* без памяти — не страшно */ }
}

document.querySelectorAll(".lang button").forEach((b) => {
  b.addEventListener("click", () => setLang(b.dataset.lang));
});

const guess = /^(ru|uk|be|kk)/i.test(navigator.language || "") ? "ru" : "en";
setLang(storedLang() || guess);

